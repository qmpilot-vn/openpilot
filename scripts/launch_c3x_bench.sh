#!/usr/bin/env bash
#
# C3X bench mode — onroad without a panda or real car.
#
# Usage:
#   ./scripts/launch_c3x_bench.sh start    # enable bench (publisher + comma restart)
#   ./scripts/launch_c3x_bench.sh stop     # revert to normal
#   ./scripts/launch_c3x_bench.sh status   # publisher + onroad state
#
# Notes:
#   - Reloads openpilot inside the comma tmux session (never systemctl restart/stop
#     comma — that kills tmux and can reboot the device on C3X bench).
#   - Writes scripts/bench_env.sh and patches launch_env.sh while active.
#   - SIMULATION=1 disables CPU affinity pinning (bench CPUs 0-3 vs onroad core 4-5).
#   - Default sim car: HONDA_CIVIC_2022 (override FINGERPRINT in bench_env if needed).
#
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null && pwd)"
OPENPILOT_ROOT="$(cd "$DIR/.." && pwd)"
LAUNCH_ENV="$OPENPILOT_ROOT/launch_env.sh"
BENCH_ENV="$DIR/bench_env.sh"
PUBLISHER="$DIR/c3x_bench_publisher.py"
PID_FILE="/tmp/c3x_bench_publisher.pid"
PUBLISHER_LOG="/tmp/c3x_bench_publisher.log"

BENCH_BEGIN="# --- c3x bench begin ---"
BENCH_END="# --- c3x bench end ---"

write_bench_env() {
  cat > "$BENCH_ENV" << 'EOF'
# Auto-generated by launch_c3x_bench.sh — do not edit
export PASSIVE=0
export NOBOARD=1
export SIMULATION=1
export SKIP_FW_QUERY=1
export FINGERPRINT=HONDA_CIVIC_2022
# reduce bench noise / avoid non-essential onroad services (same idea as tools/sim)
export BLOCK="${BLOCK},loggerd,encoderd,micd,logmessaged,manage_athenad,manage_sunnylinkd,sunnylink_uploader"
EOF
}

patch_launch_env() {
  if grep -qF "$BENCH_BEGIN" "$LAUNCH_ENV" 2>/dev/null; then
    return 0
  fi
  cat >> "$LAUNCH_ENV" << EOF

$BENCH_BEGIN
_BENCH_ENV="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)/scripts/bench_env.sh"
[ -f "\$_BENCH_ENV" ] && . "\$_BENCH_ENV"
$BENCH_END
EOF
}

unpatch_launch_env() {
  if ! grep -qF "$BENCH_BEGIN" "$LAUNCH_ENV" 2>/dev/null; then
    return 0
  fi
  awk -v begin="$BENCH_BEGIN" -v end="$BENCH_END" '
    $0 == begin { skip=1; next }
    $0 == end { skip=0; next }
    !skip { print }
  ' "$LAUNCH_ENV" > "${LAUNCH_ENV}.tmp"
  mv "${LAUNCH_ENV}.tmp" "$LAUNCH_ENV"
}

stop_publisher() {
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    if kill -0 "$pid" 2>/dev/null; then
      kill "$pid" 2>/dev/null || true
      sleep 0.5
      kill -9 "$pid" 2>/dev/null || true
    fi
    rm -f "$PID_FILE"
  fi
}

seed_params() {
  cd "$OPENPILOT_ROOT"
  export PYTHONPATH="$OPENPILOT_ROOT"
  python3 << 'PYEOF'
import cereal.messaging as messaging
from openpilot.selfdrive.test.helpers import set_params_enabled
from openpilot.common.params import Params
from openpilot.system.version import terms_version_sp

set_params_enabled()
p = Params()
p.put("HasAcceptedTermsSP", terms_version_sp)

# DeviceBootMode=1 (Always Offroad) makes manager/ui force OffroadMode=True,
# which blocks going onroad. Save it for restore on bench stop.
boot_mode = p.get("DeviceBootMode")
if boot_mode == 1:
    with open("/tmp/c3x_bench_saved_boot_mode", "w") as f:
        f.write(str(boot_mode))
    p.put("DeviceBootMode", 0)

p.put_bool("OffroadMode", False)
p.put_bool("OpenpilotEnabledToggle", True)
p.put_bool("DisableUpdates", True)

msg = messaging.new_message("liveCalibration")
msg.liveCalibration.validBlocks = 20
msg.liveCalibration.rpyCalib = [0.0, 0.0, 0.0]
p.put("CalibrationParams", msg.to_bytes())
print("bench params seeded")
PYEOF
}

start_publisher() {
  stop_publisher
  cd "$OPENPILOT_ROOT"
  export PYTHONPATH="$OPENPILOT_ROOT"
  nohup python3 "$PUBLISHER" >> "$PUBLISHER_LOG" 2>&1 &
  local i=0
  while [[ $i -lt 20 ]]; do
    if [[ -f "$PID_FILE" ]] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
      echo "publisher started (pid $(cat "$PID_FILE"), log $PUBLISHER_LOG)"
      return 0
    fi
    sleep 0.25
    i=$((i + 1))
  done
  echo "ERROR: publisher failed to start; see $PUBLISHER_LOG" >&2
  tail -20 "$PUBLISHER_LOG" >&2 || true
  return 1
}

wait_for_manager() {
  cd "$OPENPILOT_ROOT"
  export PYTHONPATH="$OPENPILOT_ROOT"
  python3 << 'PYEOF'
import cereal.messaging as messaging

sm = messaging.SubMaster(["managerState"])
for _ in range(60):
    sm.update(1000)
    if sm.all_alive({"managerState"}):
        print("manager running")
        break
else:
    raise SystemExit("manager did not start within 60s")
PYEOF
}

reload_comma() {
  if [[ ! -f /AGNOS && ! -f /TICI ]]; then
    echo "not on device (no /AGNOS or /TICI); skip comma reload"
    return 0
  fi

  # gracefully stop manager (it cleans up its child processes on SIGTERM)
  if pgrep -f "system/manager/manager.py" > /dev/null 2>&1; then
    echo "stopping manager"
    pkill -TERM -f "system/manager/manager.py" 2>/dev/null || true
    for _ in $(seq 1 20); do
      pgrep -f "system/manager/manager.py" > /dev/null 2>&1 || break
      sleep 0.5
    done
    pkill -KILL -f "system/manager/manager.py" 2>/dev/null || true
  fi

  # comma.service is Type=oneshot + RemainAfterExit, so systemctl start is a
  # no-op when it thinks it's already active. Manage the tmux session directly.
  if tmux has-session -t comma 2>/dev/null; then
    echo "respawning openpilot in comma tmux"
    tmux respawn-pane -k -t comma /data/continue.sh
  else
    echo "comma tmux session missing; creating it"
    tmux new-session -d -s comma /data/continue.sh
  fi
  wait_for_manager
}

cmd_start() {
  write_bench_env
  patch_launch_env
  reload_comma
  start_publisher
  seed_params
  echo ""
  echo "C3X bench started."
  echo "  status: $0 status"
  echo "  publisher log: tail -f $PUBLISHER_LOG"
  echo "  comma log: tail -f /tmp/launch_log"
}

restore_params() {
  cd "$OPENPILOT_ROOT"
  export PYTHONPATH="$OPENPILOT_ROOT"
  python3 << 'PYEOF'
import os
from openpilot.common.params import Params

p = Params()
saved = "/tmp/c3x_bench_saved_boot_mode"
if os.path.exists(saved):
    with open(saved) as f:
        p.put("DeviceBootMode", int(f.read().strip()))
    os.remove(saved)
    p.put_bool("OffroadMode", True)
    print("DeviceBootMode restored")
PYEOF
}

cmd_stop() {
  stop_publisher
  rm -f "$BENCH_ENV"
  unpatch_launch_env
  restore_params
  reload_comma
  echo "C3X bench stopped; normal mode restored."
}

cmd_status() {
  echo "=== C3X bench status ==="
  if [[ -f "$BENCH_ENV" ]]; then
    echo "bench_env.sh: present"
    cat "$BENCH_ENV"
  else
    echo "bench_env.sh: not present (bench not active)"
  fi
  echo ""
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    if kill -0 "$pid" 2>/dev/null; then
      echo "publisher: running (pid $pid)"
    else
      echo "publisher: stale pid file ($pid)"
    fi
  else
    echo "publisher: not running"
  fi
  echo ""
  cd "$OPENPILOT_ROOT"
  export PYTHONPATH="$OPENPILOT_ROOT"
  python3 << 'PYEOF'
import cereal.messaging as messaging

sm = messaging.SubMaster(["deviceState", "pandaStates", "managerState"])
for _ in range(40):
    sm.update(250)
    if sm.all_alive({"deviceState", "pandaStates"}):
        break

if sm.all_alive({"deviceState"}):
    print(f"deviceState.started: {sm['deviceState'].started}")
else:
    print("deviceState: not available (is comma running?)")

if sm.all_alive({"pandaStates"}) and len(sm["pandaStates"]):
    p = sm["pandaStates"][0]
    print(f"pandaStates[0].ignitionLine: {p.ignitionLine}")
    print(f"pandaStates[0].pandaType: {p.pandaType}")
else:
    print("pandaStates: not available")

if sm.updated.get("managerState") and sm.valid.get("managerState"):
    bad = [x.name for x in sm["managerState"].processes if x.shouldBeRunning and not x.running]
    print(f"manager processes not running: {bad if bad else '(none)'}")
PYEOF
}

usage() {
  echo "Usage: $0 {start|stop|status}"
  exit 1
}

chmod +x "$PUBLISHER" 2>/dev/null || true

case "${1:-}" in
  start) cmd_start ;;
  stop) cmd_stop ;;
  status) cmd_status ;;
  *) usage ;;
esac
